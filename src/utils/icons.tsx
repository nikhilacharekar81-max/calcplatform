export function getDynamicIcon(iconName?: string, props: LucideProps = { className: 'w-5 h-5' }) {
  if (!iconName) {
    return <Calculator {...props} />;
  }
  const IconComponent = AVAILABLE_ICONS[iconName] || Calculator;
  return <IconComponent {...props} />;
}
